package com.heypayments.auth.web;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.security.test.web.servlet.setup.SecurityMockMvcConfigurers.springSecurity;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.cookie;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.heypayments.BaseIntegrationTest;
import com.heypayments.auth.application.OtpService;
import com.heypayments.auth.web.dto.LoginRequest;
import com.heypayments.auth.web.dto.RegisterRequest;
import com.heypayments.auth.web.dto.SetPinRequest;
import com.heypayments.auth.web.dto.VerifyOtpRequest;
import jakarta.servlet.http.Cookie;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.MediaType;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import org.springframework.web.context.WebApplicationContext;

class AuthControllerTest extends BaseIntegrationTest {

  @Autowired private WebApplicationContext context;
  @Autowired private OtpService otpService;

  private final ObjectMapper objectMapper = new ObjectMapper();
  private MockMvc mockMvc;

  @BeforeEach
  void setUp() {
    mockMvc = MockMvcBuilders.webAppContextSetup(context).apply(springSecurity()).build();
  }

  @Test
  @DisplayName("Full auth lifecycle: register -> verify OTP -> login -> me -> refresh -> set PIN -> logout")
  void shouldCompleteFullAuthLifecycle() throws Exception {
    String phone = "+919876500001";
    String password = "SecurePassword123!";

    // 1. Register Payer
    RegisterRequest registerRequest =
        new RegisterRequest(phone, "payer.flow@example.com", password, "PAYER", "Ravi Flow");

    MvcResult regResult =
        mockMvc
            .perform(
                post("/api/v1/auth/register")
                    .contentType(MediaType.APPLICATION_JSON)
                    .content(objectMapper.writeValueAsString(registerRequest)))
            .andExpect(status().isCreated())
            .andExpect(jsonPath("$.id").exists())
            .andReturn();

    // 2. Cannot login before OTP verification
    LoginRequest prematureLogin = new LoginRequest(phone, password);
    mockMvc
        .perform(
            post("/api/v1/auth/login")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(prematureLogin)))
        .andExpect(status().isForbidden());

    // Retrieve active OTP generated by OtpService
    String activeOtp = otpService.getRecentOtpForPhone(phone);
    assertThat(activeOtp).isNotNull().matches("^\\d{6}$");

    // 3. Verify OTP
    VerifyOtpRequest verifyOtpRequest = new VerifyOtpRequest(phone, activeOtp);
    mockMvc
        .perform(
            post("/api/v1/auth/verify-otp")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(verifyOtpRequest)))
            .andExpect(status().isOk());

    // 4. Login after verification
    MvcResult loginResult =
        mockMvc
            .perform(
                post("/api/v1/auth/login")
                    .contentType(MediaType.APPLICATION_JSON)
                    .content(objectMapper.writeValueAsString(prematureLogin)))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.accessToken").exists())
            .andExpect(jsonPath("$.expiresIn").value(900))
            .andExpect(jsonPath("$.user.role").value("PAYER"))
            .andExpect(cookie().exists("hp_rt"))
            .andExpect(cookie().httpOnly("hp_rt", true))
            .andReturn();

    String responseBody = loginResult.getResponse().getContentAsString();
    String accessToken = objectMapper.readTree(responseBody).get("accessToken").asText();
    Cookie refreshCookie = loginResult.getResponse().getCookie("hp_rt");
    assertThat(refreshCookie).isNotNull();

    // 5. GET /users/me
    mockMvc
        .perform(
            get("/api/v1/users/me")
                .header("Authorization", "Bearer " + accessToken))
        .andExpect(status().isOk())
        .andExpect(jsonPath("$.phone").value(phone))
        .andExpect(jsonPath("$.role").value("PAYER"));

    // 6. Refresh token rotation
    MvcResult refreshResult =
        mockMvc
            .perform(
                post("/api/v1/auth/refresh")
                    .cookie(refreshCookie))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.accessToken").exists())
            .andExpect(cookie().exists("hp_rt"))
            .andReturn();

    Cookie rotatedCookie = refreshResult.getResponse().getCookie("hp_rt");
    assertThat(rotatedCookie.getValue()).isNotEqualTo(refreshCookie.getValue());

    // 7. Set 6-digit payment PIN
    SetPinRequest setPinRequest = new SetPinRequest("123456", password);
    mockMvc
        .perform(
            put("/api/v1/auth/pin")
                .header("Authorization", "Bearer " + accessToken)
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(setPinRequest)))
        .andExpect(status().isNoContent());

    // 8. Logout
    mockMvc
        .perform(
            post("/api/v1/auth/logout")
                .cookie(rotatedCookie))
        .andExpect(status().isNoContent())
        .andExpect(cookie().maxAge("hp_rt", 0));

    // After logout, refreshed cookie is invalid
    mockMvc
        .perform(
            post("/api/v1/auth/refresh")
                .cookie(rotatedCookie))
        .andExpect(status().isUnauthorized());
  }

  @Test
  @DisplayName("Registration rejects invalid phone format and short password")
  void shouldRejectInvalidRegistration() throws Exception {
    // Bad phone
    RegisterRequest badPhone =
        new RegisterRequest("12345", "test@example.com", "Password123!", "PAYER", "Test");
    mockMvc
        .perform(
            post("/api/v1/auth/register")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(badPhone)))
        .andExpect(status().isBadRequest())
        .andExpect(jsonPath("$.code").value("VALIDATION_FAILED"));

    // Password < 10 chars
    RegisterRequest shortPwd =
        new RegisterRequest("+919876543219", "test@example.com", "Short1!", "PAYER", "Test");
    mockMvc
        .perform(
            post("/api/v1/auth/register")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(shortPwd)))
        .andExpect(status().isBadRequest())
        .andExpect(jsonPath("$.code").value("VALIDATION_FAILED"));
  }
}
